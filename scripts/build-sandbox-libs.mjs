// Bundles guest-side libraries (chai + the `require()` allow-list) into TypeScript
// string constants that are evaluated inside the QuickJS sandbox.
// Run: npm run build:sandbox-libs   (output is deterministic and committed)
import { build } from 'esbuild';
import { writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const outDir = resolve(root, 'packages/scripting/src/generated');
const HEADER = '// GENERATED by scripts/build-sandbox-libs.mjs - do not edit. Run `npm run build:sandbox-libs`.\n';

// Node built-ins must never be bundled; inside the sandbox `require` throws for them anyway.
const NODE_BUILTINS = ['fs', 'path', 'crypto', 'module', 'util', 'os', 'stream', 'buffer', 'events', 'url', 'source-map'];

async function bundle(entry, { globalName } = {}) {
  const result = await build({
    stdin: { contents: entry, resolveDir: root, sourcefile: 'entry.js' },
    bundle: true,
    write: false,
    format: 'iife',
    ...(globalName ? { globalName } : {}),
    platform: 'neutral',
    mainFields: ['module', 'main'],
    conditions: ['import', 'default'],
    target: 'es2020',
    minify: true,
    legalComments: 'none',
    logLevel: 'error',
    external: NODE_BUILTINS,
    define: { 'process.env.NODE_ENV': '"production"' },
  });
  return result.outputFiles[0].text;
}

// ---------------------------------------------------------------- chai (evaluated at start-up)
const chaiEntry = `
import * as chai from 'chai';
globalThis.__aegisChai = { expect: chai.expect, Assertion: chai.Assertion, AssertionError: chai.AssertionError, use: chai.use };
`;
const chaiCode = await bundle(chaiEntry);
writeFileSync(resolve(outDir, 'chai-bundle.ts'), HEADER + `export const CHAI_BUNDLE: string = ${JSON.stringify(chaiCode)};\n`);
console.log(`chai bundle written (${chaiCode.length} bytes)`);

// ---------------------------------------------------------------- lazily loaded libraries
// Each library becomes `(function (crypto) { ...; return <exports>; })`: a function expression that the
// sandbox evaluates on the first `require()` and calls with a minimal `crypto.getRandomValues` shim.
// The libraries never see the host bridge; `crypto` is the only injected object.
const LIBS = {
  lodash: `import _ from 'lodash'; export default _;`,
  moment: `import moment from 'moment'; export default moment;`,
  'crypto-js': `
import CryptoJS from 'crypto-js';
// crypto-js looks for globalThis.crypto / require('crypto'); neither exists in the sandbox. Use the injected shim.
CryptoJS.lib.WordArray.random = function random(nBytes) {
  const bytes = new Uint8Array(nBytes);
  crypto.getRandomValues(bytes);
  const words = [];
  for (let i = 0; i < nBytes; i += 4) {
    words.push(((bytes[i] << 24) | ((bytes[i + 1] || 0) << 16) | ((bytes[i + 2] || 0) << 8) | (bytes[i + 3] || 0)) | 0);
  }
  return CryptoJS.lib.WordArray.create(words, nBytes);
};
export default CryptoJS;
`,
  uuid: `import * as uuid from 'uuid'; export default Object.assign({}, uuid);`,
  ajv: `
import Ajv from 'ajv';
import draft06 from 'ajv/dist/refs/json-schema-draft-06.json';
export default { Ajv, draft06 };
`,
  tv4: `import tv4 from 'tv4'; export default tv4;`,
  xml: `import { XMLParser, XMLBuilder, XMLValidator } from 'fast-xml-parser'; export default { XMLParser, XMLBuilder, XMLValidator };`,
  handlebars: `import Handlebars from 'handlebars/dist/cjs/handlebars.js'; export default Handlebars;`,
};

const entries = [];
let total = 0;
for (const [name, entry] of Object.entries(LIBS)) {
  const code = await bundle(entry, { globalName: '__aegisLibExport' });
  const wrapped = '(function (crypto) {\n' + code + '\nreturn __aegisLibExport.default;\n})';
  entries.push(`  ${JSON.stringify(name)}: ${JSON.stringify(wrapped)},`);
  total += wrapped.length;
  console.log(`${name}: ${wrapped.length} bytes`);
}
const libsOut =
  HEADER +
  '/** Lazily evaluated library bundles, keyed by internal name (see guest/libs.ts for the `require()` allow-list). */\n' +
  'export const SANDBOX_LIBS: Readonly<Record<string, string>> = {\n' +
  entries.join('\n') +
  '\n};\n';
writeFileSync(resolve(outDir, 'libs-bundle.ts'), libsOut);
console.log(`libs bundle written (${total} bytes)`);
