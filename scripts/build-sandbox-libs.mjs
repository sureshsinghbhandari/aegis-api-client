// Bundles guest-side libraries (chai) into a TypeScript string constant that is
// evaluated inside the QuickJS sandbox. Run: npm run build:sandbox-libs
import { build } from 'esbuild';
import { writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');

const entry = `
import * as chai from 'chai';
globalThis.__aegisChai = { expect: chai.expect, Assertion: chai.Assertion, AssertionError: chai.AssertionError, use: chai.use };
`;

const result = await build({
  stdin: { contents: entry, resolveDir: root, sourcefile: 'chai-entry.js' },
  bundle: true,
  write: false,
  format: 'iife',
  platform: 'neutral',
  mainFields: ['module', 'main'],
  target: 'es2020',
  minify: true,
  legalComments: 'none',
  logLevel: 'warning',
});

const code = result.outputFiles[0].text;
const out =
  '// GENERATED by scripts/build-sandbox-libs.mjs - do not edit. Run `npm run build:sandbox-libs`.\n' +
  `export const CHAI_BUNDLE: string = ${JSON.stringify(code)};\n`;
writeFileSync(resolve(root, 'packages/scripting/src/generated/chai-bundle.ts'), out);
console.log(`chai bundle written (${code.length} bytes)`);
